# -*- coding: utf-8 -*-
"""内容安全模块（阶段 7 上线加固新增）。

解决上线检查清单"内容安全"维度的核心问题：
**用户说"忽略之前的指令"时怎么办？**

设计原则（纵深防御的第 0 道闸门）：
1. **前置拦截**：在问题进入 RAG 检索 / LLM 之前做正则检测，
   命中注入特征 → 直接返回固定拒绝话术，问题根本不进模型——
   比在提示词里写"请无视注入"可靠得多（提示词约束是软的，代码拦截是硬的）。
2. **不误伤正常业务**：报销场景的合法表述（"帮我报""改成日期"等）都不在特征里；
   检测规则只匹配"试图改写 AI 身份 / 清空上下文 / 越权角色扮演"的句式。
3. **审计留痕**：命中注入的请求记入 tool_calls 日志表（tool='_injection_blocked'），
   管理员可在审计页看到攻击面。

PII 脱敏：入库/落日志前把手机号、身份证号打码，满足"报销数据脱敏"要求。
"""

import re

# ---------------------------------------------------------------------------
# 一、提示词注入特征库（正则，大小写不敏感）
# 每条都是"意图级"特征：只拦截试图改写系统指令 / 窃取提示词 / 越权角色的请求
# ---------------------------------------------------------------------------
_INJECTION_PATTERNS: list[tuple[str, re.Pattern]] = [
    # 1. 要求忽略 / 无视系统指令（最高频的注入话术）
    ("忽略指令",   re.compile(r"忽略.{0,6}(之前|上面|上述|以上|先前).{0,4}(指令|规则|提示|设定|要求)", re.I)),
    ("无视指令",   re.compile(r"无视.{0,6}(之前|上面|上述|以上|先前|所有).{0,4}(指令|规则|提示|设定|约束)", re.I)),
    ("忘记设定",   re.compile(r"(忘记|清空|删除).{0,4}(你的|之前|之前设定|系统)?(指令|设定|提示词|角色)", re.I)),
    # 2. 窃取 / 打探系统提示词（正反两种语序都覆盖）
    ("套取提示词", re.compile(r"(你的|系统)?(提示词|prompt|system prompt|初始指令).{0,8}(什么|是什么|输出|打印|泄露|告诉我)", re.I)),
    ("套取提示词", re.compile(r"(告诉我|输出|打印|泄露|看看|查看|显示).{0,6}(提示词|prompt|system prompt|初始指令)", re.I)),
    # 3. 越权角色扮演（试图让 AI 以管理员/领导口吻给放行结论）
    ("角色越权",   re.compile(r"(你现在是|假装你是|扮演|act as).{0,8}(管理员|财务总监|CEO|老板|领导|总经理|系统)", re.I)),
    # 4. 越权放行指令（直接命令系统绕过校验/审批）
    ("越权放行",   re.compile(r"(跳过|绕过|免掉|不用做).{0,8}(校验|审核|审批|验证|检查)", re.I)),
    # 5. 英文常见越狱句式（all previous 等多重修饰也覆盖）
    ("英文越狱",   re.compile(r"ignore (all|any|previous|above|prior).{0,12}(instructions|rules|prompts)|jailbreak|developer mode", re.I)),
]

# ---------------------------------------------------------------------------
# 二、PII 脱敏规则（入库前打码，保留首尾便于人工核对）
# ---------------------------------------------------------------------------
_PII_RULES: list[tuple[str, re.Pattern]] = [
    ("手机号", re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)")),
    ("身份证", re.compile(r"(?<!\d)\d{17}[\dXx](?!\d)")),
    ("银行卡", re.compile(r"(?<!\d)\d{16,19}(?!\d)")),   # 兜底长卡号（在身份证之后执行）
]


def detect_injection(question: str) -> str | None:
    """检测提示词注入。

    返回值：None = 未命中（放行）；str = 命中的规则名（拦截）。
    独立成函数便于单元测试与规则扩充（后续可加 LLM 侧二次判别）。
    """
    q = question or ""
    for name, pattern in _INJECTION_PATTERNS:
        if pattern.search(q):
            return name
    return None


def mask_pii(text: str) -> str:
    """对文本做 PII 脱敏（手机号/身份证/银行卡打码）。

    应用点：tool_calls 日志（参数与结果摘要落库前）。
    注意只处理"将要持久化的日志文本"，不改动送入模型的原始内容，
    避免脱敏破坏金额数字导致校验结果失真。
    """
    if not text:
        return text
    out = text
    for name, pattern in _PII_RULES:
        # 手机号/身份证保留前 3 后 2；卡号保留前 4 后 4
        keep = 2 if name != "银行卡" else 4
        out = pattern.sub(lambda m: _mask(m.group(0), keep), out)
    return out


def _mask(s: str, keep: int) -> str:
    """打码：保留首尾 keep 位，中间用 * 填充。"""
    if len(s) <= keep * 2:
        return "*" * len(s)
    return s[:keep] + "*" * (len(s) - keep * 2) + s[-keep:]
